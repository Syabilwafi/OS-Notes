import os
import re

# Raw glossary content provided
raw_glossary = """
### **A**

- **Application Programs**: Software (such as web browsers, word processors, or database systems) that defines how system resources are used to solve user computing problems.
- **Asymmetric Multiprocessing**: A multiprocessing system model where each processor is assigned a specific task, governed by a master processor.

### **B**

- **Binary Search Tree (BST)**: A data structure where each node has at most two children, organized such that left children are less than or equal to right children; used within kernels.
- **Bit**: The basic unit of computer storage, containing a value of 0 or 1.
- **Bitmap**: A sequence or string of $n$ binary digits representing the status of $n$ items.
- **Bootstrap Program**: The initial, simple code loaded at power-up or reboot that initializes the computer system and loads the operating system kernel.
- **Byte**: A collection of 8 bits; the smallest convenient chunk of storage on most computers.

### **C**

- **Cache Coherency**: A hardware mechanism in multiprocessor environments ensuring all CPUs maintain the most up-to-date value of data in their local caches.
- **Caching**: The practice of copying information from slower, larger storage to faster, smaller storage temporarily to improve performance.
- **Clustered System**: An architecture that links multiple independent computers together (often sharing storage via a SAN) to provide high availability or high-performance computing.
- **Device Controller**: Hardware components connected to the system bus that manage specific types of I/O devices and maintain local buffers.
- **Device Driver**: A software layer provided for each device controller that manages I/O operations and presents a uniform interface to the operating system kernel.

### **D**

- **Direct Memory Access (DMA)**: A high-speed I/O mechanism that allows a device controller to transfer blocks of data directly to/from main memory without continuous CPU intervention.
- **Distributed System**: A network-connected collection of separate, potentially heterogeneous computing systems that exchange messages to coordinate work.
- **Dual-Mode Operation**: A hardware-supported feature using a mode bit to distinguish between user mode (running user applications) and kernel mode (running OS code), protecting the system from unauthorized access.

### **E**

- **Emulation**: Translating instructions from one CPU architecture type to run on another (e.g., executing PowerPC code on Intel x86).

### **H**

- **Hard Disk Drive (HDD)**: Non-volatile secondary storage consisting of rigid magnetic platters divided logically into tracks and sectors.
- **Hash Map**: A data structure that uses a hash function to map keys to values for fast data retrieval within the kernel.

### **I**

- **Infrastructure as a Service (IaaS)**: A cloud computing delivery model providing raw computing infrastructure—such as virtual servers or storage—over the Internet.
- **Interrupt**: A signal generated by hardware (or software) to notify the CPU that an event requires immediate attention, causing a switch to an interrupt service routine.
- **Interrupt Vector**: An array or table containing the memory addresses of all the interrupt service routines.

### **K**

- **Kernel**: The core program of an operating system that runs at all times on the computer hardware.
- **Kernel Mode**: A privileged CPU execution state ($\text{mode bit} = 0$) where all instructions and hardware access are permitted.

### **M**

- **Main Memory (RAM)**: The primary volatile random-access storage directly accessible by the CPU to read instructions and data.
- **Middleware**: Software frameworks that ship with or complement operating systems to provide extra services to application developers (e.g., database engines, graphics frameworks).
- **Multiprogramming**: A technique where multiple jobs are held in memory simultaneously so that when one job waits (e.g., for I/O), the OS switches the CPU to another job.
- **Multitasking (Timesharing)**: A logical extension of multiprogramming where the CPU switches tasks so rapidly that users can interact with each program while it runs.

### **N**

- **Non-Uniform Memory Access (NUMA)**: System architecture where memory access times vary depending on which CPU core accesses which memory module.
- **Non-Volatile Memory (NVM)**: Storage media that retains saved data even when power is removed (e.g., SSDs, flash memory, HDDs).

### **O**

- **Operating System (OS)**: A program that acts as an intermediary between the user of a computer and the computer hardware, managing resources efficiently and facilitating program execution.

### **P**

- **Platform as a Service (PaaS)**: A cloud service offering a ready-to-use software stack (such as a database management system) over the network.
- **Privileged Instruction**: An instruction that can only be executed when the CPU is in kernel mode to ensure system protection.
- **Process**: A program in execution; an active entity with a program counter and resources allocated to it.
- **Protection**: Any mechanism for controlling access by processes or users to resources defined by the operating system.

### **R**

- **Real-Time Operating System**: An operating system designed for embedded systems with strict, well-defined time constraints where processing must be completed within exact deadlines.

### **S**

- **Secondary Storage**: Non-volatile storage extensions used to back up main memory and store large amounts of data permanently (e.g., HDDs, NVM/SSDs).
- **Security**: Defensive measures that protect a computing system against internal or external malicious attacks.
- **Software as a Service (SaaS)**: A cloud computing service where one or more end-user software applications are delivered across the Internet.
- **Storage-Area Network (SAN)**: A specialized, high-speed network linking multiple storage devices to multiple servers, common in clustered computing environments.
- **Symmetric Multiprocessing (SMP)**: A multiprocessor layout where all processors perform any task within the system and share main memory equally.
- **System Call**: A request mechanism used by a user process to request services directly from the operating system kernel, switching the processor to kernel mode.

### **T**

- **Timer**: A hardware counter set by the OS (via privileged instructions) that decrements over time and interrupts the CPU when reaching zero, preventing user programs from hogging the CPU or running in infinite loops.
- **Trap (Exception)**: A software-generated interrupt caused either by an error (e.g., division by zero) or a deliberate request from a user program (via a system call).

### **U**

- **User Mode**: An unprivileged execution state ($\text{mode bit} = 1$) for executing standard software and user processes.

### **V**

- **Virtual Machine Manager (VMM / Hypervisor)**: Software that manages system virtualization by allowing multiple guest operating systems to run natively on a single hardware host.
- **Virtual Memory**: A memory management capability that allows the execution of processes that are not completely loaded into physical main memory.
- **Volatile Storage**: Storage media that loses its contents when power is turned off or interrupted (e.g., main memory, registers, cache).

### **W**

- **Word**: A computer architecture's native unit of data, typically matching its register size (e.g., 64 bits / 8 bytes on a 64-bit machine).
"""

OUTPUT_DIR = "Glossary Terms"

def create_term_files():
    # Ensure target output directory exists
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    
    # Match bullet lines like: - **Term Name**: Definition text
    pattern = r"^\s*-\s*\*\*(.*?)\*\*\s*:\s*(.*)$"
    
    count = 0
    for line in raw_glossary.splitlines():
        match = re.match(pattern, line)
        if match:
            term = match.group(1).strip()
            definition = match.group(2).strip()
            
            # Clean invalid filename characters reserved by OS file systems or Obsidian
            filename_clean = re.sub(r'[\\/:*?"<>|]', "", term)
            file_path = os.path.join(OUTPUT_DIR, f"{filename_clean}.md")
            
            # Obsidian term note template with Frontmatter YAML properties
            content = f"""---
tags:
  - glossary
  - os-concepts
---
{definition}
"""
            with open(file_path, "w", encoding="utf-8") as f:
                f.write(content)
            
            count += 1

    print(f"Successfully generated {count} Obsidian term files in standard path: '{OUTPUT_DIR}/'")

if __name__ == "__main__":
    create_term_files()